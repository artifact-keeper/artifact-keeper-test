#!/usr/bin/env python3
# =============================================================================
# build_fixtures.py <out-dir>
#   Maven archives for the scan-grading-os-and-jar-trivy tier
# =============================================================================
# Writes every file the tier's Maven Remote fetches into <out-dir> and an
# index, <out-dir>/files.tsv, with one line per file:
#     <upstream path>\t<local file>\t<content type>
# The oracle PUTs each one into the mock-files upstream (profiles/
# upstreams.mock-files.yml) at that path. The archives are built with fixed
# timestamps, so the bytes and digests are the same on every run. The JAR
# and POM builders are those of scan-grading-os-and-jar/fixtures. Stdlib only.
#
# Maven (Remote upstream /maven2)
#   com/example/dtfgrade/dtf-declared-only/1.0.0/dtf-declared-only-1.0.0.jar
#       its own pom.properties, and a build POM (META-INF/maven/.../pom.xml)
#       that declares org.apache.logging.log4j:log4j-core:2.14.1 and
#       com.fasterxml.jackson.core:jackson-databind:2.9.8 in compile scope.
#       Neither is bundled: the JAR carries one class of its own (#6233).
#   org/apache/logging/log4j/log4j-core/2.14.1/log4j-core-2.14.1.jar
#       its own coordinate is Log4Shell (control)
#   com/example/dtfgrade/dtf-grade-webapp/1.0.0/dtf-grade-webapp-1.0.0.war
#       its own pom.properties, a build POM declaring log4j-core 2.14.1, and
#       that library bundled as WEB-INF/lib/logging.jar with no
#       pom.properties, no manifest and no version in its name: nothing but
#       the WAR's build POM names it (control)
#   com/example/dtfgrade/dtf-no-props/1.0.0/dtf-no-props-1.0.0.jar
#       a build POM declaring log4j-core 2.14.1 and no pom.properties, so the
#       POM is the only record of the archive (control)
# =============================================================================
import hashlib
import io
import os
import sys
import zipfile

OUT = sys.argv[1]
FIXED = (2020, 1, 1, 0, 0, 0)
INDEX = []
LOG4J = ("org.apache.logging.log4j", "log4j-core", "2.14.1", "compile")
JACKSON = ("com.fasterxml.jackson.core", "jackson-databind", "2.9.8", "compile")


def emit(path, data, ctype="application/octet-stream"):
    data = data.encode() if isinstance(data, str) else data
    local = os.path.join(OUT, f"f{len(INDEX):04d}")
    with open(local, "wb") as f:
        f.write(data)
    INDEX.append((path, local, ctype))
    return data


def zip_bytes(entries):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in entries:
            info = zipfile.ZipInfo(name, date_time=FIXED)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    return buf.getvalue()


def pom(group, artifact, version, packaging="jar", deps=()):
    d = "".join(
        f"    <dependency>\n      <groupId>{g}</groupId>\n      <artifactId>{a}</artifactId>\n"
        f"      <version>{v}</version>\n      <scope>{sc}</scope>\n    </dependency>\n"
        for g, a, v, sc in deps
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<project xmlns="http://maven.apache.org/POM/4.0.0">\n'
        "  <modelVersion>4.0.0</modelVersion>\n"
        f"  <groupId>{group}</groupId>\n  <artifactId>{artifact}</artifactId>\n"
        f"  <version>{version}</version>\n  <packaging>{packaging}</packaging>\n"
        + (f"  <dependencies>\n{d}  </dependencies>\n" if deps else "")
        + "</project>\n"
    )


def maven(group, artifact, version, packaging="jar", deps=(), props=True, extra=()):
    p = pom(group, artifact, version, packaging, deps)
    meta = f"META-INF/maven/{group}/{artifact}"
    entries = [("META-INF/MANIFEST.MF", "Manifest-Version: 1.0\nCreated-By: dtf\n\n")]
    if props:
        entries.append(
            (
                f"{meta}/pom.properties",
                f"#Generated by Maven\ngroupId={group}\nartifactId={artifact}\nversion={version}\n",
            )
        )
    entries.append((f"{meta}/pom.xml", p))
    entries.append(("dtf/Dtf.class", b"\xca\xfe\xba\xbe"))
    entries.extend(extra)
    archive = zip_bytes(entries)
    ext = "war" if packaging == "war" else "jar"
    base = f"/maven2/{group.replace('.', '/')}/{artifact}/{version}/{artifact}-{version}"
    emit(f"{base}.{ext}", archive)
    emit(f"{base}.{ext}.sha1", hashlib.sha1(archive).hexdigest(), "text/plain")
    emit(base + ".pom", p, "application/xml")
    emit(base + ".pom.sha1", hashlib.sha1(p.encode()).hexdigest(), "text/plain")


maven("com.example.dtfgrade", "dtf-declared-only", "1.0.0", deps=[LOG4J, JACKSON])
maven("org.apache.logging.log4j", "log4j-core", "2.14.1")
maven(
    "com.example.dtfgrade", "dtf-grade-webapp", "1.0.0", "war",
    deps=[LOG4J],
    extra=[
        (
            "WEB-INF/lib/logging.jar",
            zip_bytes([("org/apache/logging/log4j/core/Logger.class", b"\xca\xfe\xba\xbe")]),
        )
    ],
)
maven("com.example.dtfgrade", "dtf-no-props", "1.0.0", deps=[LOG4J], props=False)

with open(os.path.join(OUT, "files.tsv"), "w") as f:
    for p, local, ct in INDEX:
        f.write(f"{p}\t{local}\t{ct}\n")
print(len(INDEX))
