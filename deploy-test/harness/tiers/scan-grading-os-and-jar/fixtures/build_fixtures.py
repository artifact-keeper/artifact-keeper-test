#!/usr/bin/env python3
# =============================================================================
# build_fixtures.py <out-dir>
#   Alpine, Debian, RPM and Maven packages for the scan-grading-os-and-jar tier
# =============================================================================
# Writes every file the tier's Remotes fetch into <out-dir> and an index,
# <out-dir>/files.tsv, with one line per file:
#     <upstream path>\t<local file>\t<content type>
# The oracle PUTs each one into the mock-files upstream (profiles/
# upstreams.mock-files.yml) at that path. Every archive is built with fixed
# timestamps, so the bytes and digests are the same on every run. The package
# builders are those of scan-on-proxy-maven-nuget/fixtures/mock_scan_upstream.py
# (an ar .deb, an RPM v3 lead + headers + cpio.gz payload, a signed .apk of
# three gzip members). Stdlib only.
#
# Alpine (Remote upstream /alpine), branch v3.22
#   curl-8.14.1-r4.apk     origin curl                         (control)
#   libcurl-8.14.1-r4.apk  origin curl: a subpackage whose own CPE
#                          (libcurl:libcurl) NVD does not file curl under (#5236)
# Debian (Remote upstream /debian), suite bookworm (Release: Debian 12.7),
#   whose Release names the served main/binary-amd64/Packages
#   pool/main/o/openssl/openssl_3.0.11-1~deb12u2_amd64.deb   listed (control; #5628)
#   pool/main/d/dtf-gradeclean/dtf-gradeclean_1.0-1_amd64.deb listed (control)
#   pool/main/d/dtf-oldmark/dtf-oldmark_1.0-1+deb11u1_amd64.deb
#                          listed in the bookworm index, but its version
#                          marker names Debian 11 (#5170 item 1)
#   pool/main/d/dtf-unlisted/dtf-unlisted_1.0-1_amd64.deb
#                          unmarked and listed by NO index (#5170 item 2)
# RPM (Remote upstream /rpm), under 9/BaseOS/x86_64/os/
#   Packages/o/openssl-libs-3.0.7-17.el9_2.x86_64.rpm  epoch 1, RHEL 9 (#5628)
#   repodata/repomd.xml
# Maven (Remote upstream /maven2)
#   com/example/dtfgrade/dtf-grade-plugin/1.0.0/dtf-grade-plugin-1.0.0.jar
#       its own pom.properties, and a build POM (META-INF/maven/.../pom.xml)
#       that declares org.apache.maven:maven-core:3.2.5 `provided` and
#       org.apache.maven:maven-compat:3.2.5 `test` (#5262)
#   org/apache/logging/log4j/log4j-core/2.14.1/log4j-core-2.14.1.jar
#       its own coordinate is Log4Shell (control)
# =============================================================================
import gzip
import hashlib
import io
import os
import sys
import tarfile
import zipfile

OUT = sys.argv[1]
FIXED = (2020, 1, 1, 0, 0, 0)
INDEX = []


def emit(path, data, ctype="application/octet-stream"):
    data = data.encode() if isinstance(data, str) else data
    local = os.path.join(OUT, f"f{len(INDEX):04d}")
    with open(local, "wb") as f:
        f.write(data)
    INDEX.append((path, local, ctype))
    return data


def tar_raw(entries, eof=True):
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.USTAR_FORMAT) as t:
        for name, data in entries:
            data = data.encode() if isinstance(data, str) else data
            ti = tarfile.TarInfo(name)
            ti.size = len(data)
            ti.mtime = 1577836800
            ti.mode = 0o644
            t.addfile(ti, io.BytesIO(data))
    out = raw.getvalue()
    if not eof:
        out = out.rstrip(b"\0")
        out += b"\0" * ((-len(out)) % 512)
    return out


# ------------------------------------------------------------------ Alpine
def apk_bytes(pkgname, pkgver, arch="x86_64", origin=None):
    info = (
        f"# Generated by dtf\npkgname = {pkgname}\npkgver = {pkgver}\n"
        f"pkgdesc = dtf scan fixture\narch = {arch}\nlicense = MIT\n"
    )
    if origin:
        info += f"origin = {origin}\n"
    sig = gzip.compress(tar_raw([(".SIGN.RSA.dtf.rsa.pub", b"not a signature")], eof=False), mtime=0)
    ctl = gzip.compress(tar_raw([(".PKGINFO", info)], eof=False), mtime=0)
    data = gzip.compress(tar_raw([("usr/share/doc/" + pkgname + "/README", "dtf\n")]), mtime=0)
    return sig + ctl + data


for name in ("curl", "libcurl"):
    emit(f"/alpine/v3.22/main/x86_64/{name}-8.14.1-r4.apk", apk_bytes(name, "8.14.1-r4", origin="curl"))


# ------------------------------------------------------------------ Debian
def ar_member(name, data):
    head = f"{name:<16}{0:<12}{0:<6}{0:<6}{'100644':<8}{len(data):<10}`\n".encode()
    return head + data + (b"\n" if len(data) % 2 else b"")


def deb_bytes(package, version, arch="amd64"):
    control = (
        f"Package: {package}\nVersion: {version}\nArchitecture: {arch}\n"
        "Maintainer: DTF <dtf@example.invalid>\nDescription: dtf scan fixture\n"
    )
    ctl = gzip.compress(tar_raw([("./control", control)]), mtime=0)
    data = gzip.compress(tar_raw([("./usr/share/doc/" + package + "/README", "dtf\n")]), mtime=0)
    return b"!<arch>\n" + ar_member("debian-binary", b"2.0\n") + ar_member(
        "control.tar.gz", ctl
    ) + ar_member("data.tar.gz", data)


def deb(package, version, source=None):
    src = source or package
    path = f"pool/main/{src[0]}/{src}/{package}_{version}_amd64.deb"
    body = emit(f"/debian/{path}", deb_bytes(package, version))
    return path, package, version, body


